import type { 附魔数据类型 } from '@/@types/附魔'
import { 属性类型 } from '@/@types/属性'

// 仅过滤配装器候选，旧配装的附魔仍可正常识别和计算。
export const 五十级附魔可见 = (附魔: 附魔数据类型) =>
  !/力道|元气|身法|根骨/.test(附魔.附魔名称) &&
  !附魔.增益集合?.some(
    ({ 属性, 值 }) =>
      Number(值) === 36 || Number(值) === 29 || (属性 === 属性类型.无双等级 && Number(值) === 22),
  )

const 获取附魔排序数值 = (附魔: 附魔数据类型) =>
  Math.max(0, ...(附魔.增益集合 || []).map(({ 值 }) => Number(值)).filter(Number.isFinite))

export const 附魔数值降序 = (前: 附魔数据类型, 后: 附魔数据类型) =>
  获取附魔排序数值(后) - 获取附魔排序数值(前)

// 仅合并展示文字，附魔名称仍作为原有存储值使用。
export const 格式化附魔名称 = (名称 = '') =>
  名称
    .replace(/[（(][^（）()]*[）)]\s*[（(]([^（）()]*\+[^（）()]*)[）)]$/, '（$1）')
    .replace(/内外功攻击/g, '全攻击')
    .replace(/\s*\+\s*/g, '+')

export const 格式化附魔数值 = (名称 = '') => {
  const 显示名称 = 格式化附魔名称(名称)
  return 显示名称.match(/[（(]([^（）()]*\+[^（）()]*)[）)]$/)?.[1] || 显示名称
}
