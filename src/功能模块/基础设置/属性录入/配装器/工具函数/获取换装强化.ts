import type { 装备属性信息模型, 选择装备数据类型 } from '@/@types/装备'
import { 获取最大精炼等级 } from './获取最大精炼等级'

export function 获取换装强化(
  装备: 装备属性信息模型 | undefined,
  当前装备: Partial<Pick<选择装备数据类型, '镶嵌孔数组'>> | undefined,
  默认镶嵌宝石等级: number,
) {
  return {
    当前精炼等级: 获取最大精炼等级(装备),
    镶嵌孔数组: 装备?.镶嵌孔数组?.map((孔, 索引) => ({
      ...孔,
      镶嵌宝石等级: 当前装备?.镶嵌孔数组?.[索引]?.镶嵌宝石等级 || 默认镶嵌宝石等级,
    })),
  }
}
