const 技能统计名称: Record<string, string> = {
  '14701': '净世破魔击·日',
  '4476': '净世破魔击·月',
  '4028': '赤日轮',
  '4029': '赤日轮',
  '4030': '赤日轮',
  '13359': '银月斩（dot）',
  '42565': '无量妙境',
  '42566': '无量妙境',
}

// 使用原项目统计名称合并显示，保留各分项的计算名称和独立结算。
export function 获取明尊技能显示信息(技能ID: string | number) {
  const 统计名称 = 技能统计名称[String(技能ID)]
  return 统计名称 ? { 统计名称, ...(String(技能ID) === '13359' ? { 显示名称: 统计名称 } : {}) } : {}
}
