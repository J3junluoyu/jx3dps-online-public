import { 数据模块类型 } from '@/store/data'
import {
  加载缓存全部方案数据,
  加载缓存团队增益轴,
  加载缓存当前方案名称,
  加载缓存当前输出计算目标名称,
  加载缓存网络延迟,
  加载缓存背景图片显示状态,
  加载缓存自定义循环数据,
  获取方案内信息,
} from './缓存函数'
import { 系统模块类型 } from '@/store/system'
import 获取当前数据 from '@/数据/数据工具/获取当前数据'
import {
  自适应光明心循环名称,
  根据明尊循环同步奇穴,
} from '@/心法模块/心法/明尊琉璃体/计算循环/循环联动'

export const 获取数据默认值 = () => {
  const 默认数据: 数据模块类型 = {
    当前方案名称: 加载缓存当前方案名称(),
    全部方案数据: 加载缓存全部方案数据(),
    // 方案内信息
    角色基础属性: 获取方案内信息('角色基础属性'),
    装备信息: 获取方案内信息('装备信息'),
    增益启用: 获取方案内信息('增益启用'),
    增益数据: 获取方案内信息('增益数据'),
    当前奇穴信息: 获取方案内信息('当前奇穴信息'),
    当前秘籍信息: 获取方案内信息('当前秘籍信息'),
    当前计算循环名称: 获取方案内信息('当前计算循环名称'),
    // 其他信息
    团队增益轴: 加载缓存团队增益轴(),
    网络延迟: 加载缓存网络延迟(),
    当前输出计算目标名称: 加载缓存当前输出计算目标名称(),
    自定义循环列表: 加载缓存自定义循环数据(),
    当前计算结果: { 秒伤: 0, 总伤: 0, 秒伤计算时间: 0, 计算结果技能列表: [] },
  }
  if (获取当前数据().名称 === '明尊琉璃体') {
    // 进入计算器时使用光明心奇穴与自适应循环。
    默认数据.当前计算循环名称 = 自适应光明心循环名称
    默认数据.当前奇穴信息 = 根据明尊循环同步奇穴(自适应光明心循环名称, 默认数据.当前奇穴信息)
    const 当前方案 = 默认数据.全部方案数据?.[默认数据.当前方案名称]
    if (当前方案) {
      默认数据.全部方案数据 = {
        ...默认数据.全部方案数据,
        [默认数据.当前方案名称]: {
          ...当前方案,
          当前计算循环名称: 默认数据.当前计算循环名称,
          当前奇穴信息: [...默认数据.当前奇穴信息],
        },
      }
    }
  }
  return 默认数据
}

export const 获取系统默认值 = () => {
  const 默认系统配置: 系统模块类型 = {
    新手引导流程状态: false,
    背景图片显示状态: 加载缓存背景图片显示状态(),
    增益面板显示状态: false,
    当前引导步骤: 0,
    配装器弹窗显示状态: false,
  }
  return 默认系统配置
}
