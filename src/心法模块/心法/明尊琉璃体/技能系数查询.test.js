import { 获取明尊技能系数 } from './技能系数查询'

const 查询 = (基础体质, 增伤) => Object.fromEntries(
  获取明尊技能系数(基础体质, 增伤).map((行) => [行.名称, 行]),
)

test('固定基础仇恨按现行技能分段读取，独立于面板体质和手填增伤', () => {
  const 行 = 查询(12000, { 4476: 25, 44567: 30 })
  expect([1, 2, 3].map((段) => 行[`赤日轮·${段}段`].基础仇恨值)).toEqual([2031, 2031, 2854])
  expect([1, 2, 3].map((段) => 行[`幽月轮·${段}段`].基础仇恨值)).toEqual([1761, 1761, 2513])
  expect(行.烈日斩.基础仇恨值).toBe(5241)
  expect(行.银月斩.基础仇恨值).toBe(4143)
  expect(行['净世破魔击·月']).toMatchObject({ 基础仇恨值: 4129, 段数: 3 })
  expect(行['净世破魔击·日']).toMatchObject({ id: '14701', 基础仇恨值: null })
  expect(行['银月斩·DOT'].基础仇恨值).toBeUndefined()
  expect(行.戒火斩.基础仇恨值).toBe(2394)
  expect(查询(0).戒火斩.基础仇恨值).toBe(2394)
})

test('日月轮逐段列出，月破按三段折算，无量妙境和净体不畏按单段', () => {
  const 行 = 查询(0, { 4476: 25, 42565: 20, 26708: 10 })
  expect(Object.keys(行)).toHaveLength(16)
  const 轮 = Object.keys(行).filter((名称) => /^(赤日|幽月)轮/.test(名称))
  expect(轮).toEqual(['赤日轮·1段', '赤日轮·2段', '赤日轮·3段', '幽月轮·1段', '幽月轮·2段', '幽月轮·3段'])
  expect(行['净世破魔击·月'].基础系数).toBeCloseTo(0.17324003325, 10)
  expect(行['净世破魔击·月'].实际系数).toBeCloseTo(0.17324003325 * 3 * 1.25, 10)
  expect(行.无量妙境.实际系数).toBeCloseTo(0.34519203651 * 1.2, 10)
  expect(行.净体不畏.实际系数).toBeCloseTo(0.17195200326 * 1.1, 10)
  expect(Object.values(行).every(({ 实际系数 }) => Number.isFinite(实际系数))).toBe(true)
})

test('银月斩直伤和DOT分别列出，DOT单跳基础系数按完整9跳及独立增伤换算', () => {
  const 行 = 查询(0, { 40089: 10, 13359: 25 })
  expect(行.银月斩.实际系数).toBeCloseTo(0.18483230313260227 * 1.1, 10)
  expect(行['银月斩·DOT'].基础系数).toBeCloseTo(0.0369235262936209, 10)
  expect(行['银月斩·DOT'].段数).toBe(9)
  expect(行['银月斩·DOT'].实际系数).toBeCloseTo(0.0369235262936209 * 9 * 1.25, 10)
})

test('驱夜断愁按客户端帧数分别显示正面和背后系数', () => {
  const 行 = 查询(0, { 4480: 10 })
  expect(行['驱夜断愁·正面'].基础系数).toBeCloseTo(814 / (16 * 97.04743), 12)
  expect(行['驱夜断愁·正面'].实际系数).toBeCloseTo((814 / (16 * 97.04743)) * 1.1, 12)
  expect(行['驱夜断愁·背后'].实际系数).toBeCloseTo(1059 / (16 * 97.04743), 12)
})

test('戒火斩保留基础系数并按面板基础体质档位与手填增伤计算实际系数', () => {
  const 基础 = 查询(959).戒火斩
  expect(基础.实际系数).toBe(基础.基础系数)
  expect(查询(960).戒火斩.实际系数).toBeCloseTo(基础.基础系数 * 2, 10)
  expect(查询(9600, { 44567: 30 }).戒火斩).toMatchObject({ 基础系数: 基础.基础系数, 段数: 1 })
  expect(查询(12000, { 44567: 30 }).戒火斩.实际系数).toBeCloseTo(基础.基础系数 * 11 * 1.3, 10)
})
