jest.mock('@/数据/数据工具/获取当前数据', () => ({
  __esModule: true,
  default: () => ({
    名称: '明尊琉璃体',
    基础GCD: 1,
    计算循环: require('./计算循环').default,
    小药小吃: require('./增益').明尊小药小吃,
  }),
}))

import useCycle from '@/hooks/use-cycle'
import 循环列表 from './计算循环'
import { 明尊小药小吃 } from './增益'

const 手动循环 = {
  ...循环列表[0],
  名称: '手动循环',
  循环详情: [{ 战斗时间: 60, 技能详情: [] }],
}
const 选择 = (加速, 覆盖 = {}) =>
  useCycle({
    使用内存数据: false,
    覆盖数据: {
      装备信息: { 装备基础属性: { 加速等级: 加速 } },
      当前计算循环名称: 手动循环.名称,
      自定义循环列表: [手动循环],
      ...覆盖,
    },
  })

test.each([
  [1451, '手动循环'],
  [1452, '0.8125GCD循环'],
  [2339, '0.8125GCD循环'],
  [2340, '0.75GCD循环'],
  [10000, '0.75GCD循环'],
])('加速%s按实际帧数选择%s，覆盖两个节点及相邻档位', (加速, 名称) => {
  const 结果 = 选择(加速)
  expect(结果.当前循环信息.名称).toBe(名称)
  expect(结果.计算循环详情.战斗时间).toBe(名称 === '手动循环' ? 60 : 300)
})

test('启用的加速药品跨过节点时自动切换，关闭增益后不计药品加速', () => {
  const 药品 = 明尊小药小吃.find((项) => 项.考拉属性.haste_base === 203)
  const 增益数据 = { 小吃: [药品.小吃名称], 团队增益: [], 阵眼: '' }
  expect(选择(1249, { 增益数据, 增益启用: true }).当前循环信息.名称).toBe('0.8125GCD循环')
  expect(选择(2137, { 增益数据, 增益启用: true }).当前循环信息.名称).toBe('0.75GCD循环')
  expect(选择(2137, { 增益数据, 增益启用: false }).当前循环信息.名称).toBe('0.8125GCD循环')
})

test('切换GCD时同时切换实际计算次数，不只更新循环名称', () => {
  const 结果 = 选择(2340, { 当前计算循环名称: '0.8125GCD循环' })
  expect(结果.当前循环信息.名称).toBe('0.75GCD循环')
  expect(结果.计算循环详情.技能详情.find((项) => 项.技能名称 === '驱夷日破').技能数量).toBe(52)
  expect(结果.计算循环详情.技能详情.find((项) => 项.技能名称 === '武伤').技能数量).toBe(407)
  expect(选择(1452, { 当前计算循环名称: '0.75GCD循环' }).当前循环信息.名称).toBe('0.8125GCD循环')
})

test('同档位自定义次数可正常使用，跨档后自动选择对应预设', () => {
  const 自定义 = { ...手动循环, 循环详情: [{ ...手动循环.循环详情[0], 循环加速等级: 3 }] }
  expect(选择(1452, { 自定义循环列表: [自定义] }).当前循环信息).toBe(自定义)
  expect(选择(2340, { 自定义循环列表: [自定义] }).当前循环信息.名称).toBe('0.75GCD循环')
})

test('旧循环名称和已移除的缓存不再出现在可选列表，旧名称按当前档位解析', () => {
  const 已删除 = ['明尊自定义命中次数', '迁移的明尊命中次数'].map((名称) => ({ ...手动循环, 名称 }))
  const 结果 = 选择(1452, { 当前计算循环名称: '明尊基础循环（300秒）', 自定义循环列表: 已删除 })
  expect(结果.全部循环.map((项) => 项.名称)).toEqual(['0.8125GCD循环', '0.75GCD循环'])
  expect(结果.当前循环信息.名称).toBe('0.8125GCD循环')
})
