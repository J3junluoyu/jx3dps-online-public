test('主界面保存的宏使用节点结算，手填覆盖率不参与但改层数和开关会生效', () => {
  const 宏方案 = { 循环宏: '/cast 赤日轮' }
  const 逐招配置 = { ...生成(宏方案, 40), 宏方案 }
  const 输入 = {
    装备信息: { 装备列表: [{ id: '1' }], 装备基础属性: { 明尊属性: { ...装备, strain: 0 } } },
    奇穴: 起手.奇穴, 目标等级: 54, 秘籍: {}, 技能列表: [],
    战斗时间: 40, 循环名称: '测试宏', 逐招配置,
  }
  const 计算 = (层数, 覆盖率, 启用 = true, 增益启用 = true, 配置 = 逐招配置, 计算技能详情 = true) => 明尊秒伤计算({
    ...输入, 增益启用, 逐招配置: 配置, 计算技能详情,
    增益数据: { 团队增益: [{ 增益名称: '仙王蛊鼎', 层数, 覆盖率, 启用 }] },
  })
  const 节点计算 = 计算(35, 0)
  expect(节点计算.循环内增益.覆盖).toEqual([{ 名称: '仙王蛊鼎', 覆盖率: 75 }])
  expect(计算(35, 0, true, true, 逐招配置, false)).toEqual({
    ...节点计算, 计算结果技能列表: [],
  })
  expect(计算(35, 99)).toEqual(节点计算)
  expect(计算(10, 0).秒伤).toBeLessThan(节点计算.秒伤)
  expect(计算(35, 0, false).循环内增益).toBeUndefined()
  expect(计算(35, 0, true, false)).toEqual(计算(35, 0, false))
  expect(计算(35, 0, true, true, { ...逐招配置, 默认宏团队增益: false })).toEqual(节点计算)
  const 手编循环 = { ...逐招配置, 宏自动重排: false }
  expect(计算(35, 0, true, true, 手编循环)).toEqual(节点计算)
  expect(计算(35, 99, true, true, 手编循环)).toEqual(节点计算)
  expect(计算(35, 99, false, true, 手编循环).循环内增益).toBeUndefined()
})

