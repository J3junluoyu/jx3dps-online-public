export interface 基础循环技能类型 {
  技能名称: string
  默认次数: number
  技能: Skill
  命中倍率: number
  驱夷: boolean
  光明相: boolean
  五明: boolean
  单位: string
}

const 创建技能 = (
  技能名称: keyof ReturnType<typeof 推导基础循环次数>,
  原始键: string,
  设置: Partial<Omit<基础循环技能类型, '技能名称' | '技能' | '默认次数'>> = {},
): 基础循环技能类型 => {
  const 技能 = SKILLS.find((项) => 项.key === 原始键)
  if (!技能) throw new Error(`基础循环缺少技能：${原始键}`)
  return {
    技能名称,
    默认次数: 基础循环次数[技能名称],
    技能,
    命中倍率: 1,
    驱夷: false,
    光明相: false,
    五明: false,
    单位: '施放',
    ...设置,
  }
}

