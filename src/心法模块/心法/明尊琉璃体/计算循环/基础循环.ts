export const 使用基础循环格式 = (列表: 循环技能详情[] = []) =>
  列表.some((项) => 项.技能名称 === '驱夷日破')

export const 创建基础循环行 = (技能: 基础循环技能类型, 技能数量: number): 循环技能详情 => ({
  技能名称: 技能.技能名称,
  技能数量,
  技能增益列表: [
    ...(技能.驱夷 ? ['驱夷逐法'] : []),
    ...(技能.光明相 ? ['光明相'] : []),
    ...(技能.五明 ? ['五明乐见'] : []),
  ].map((增益名称) => ({ 增益名称, 增益技能数: 技能数量 })),
})

export function 创建明尊基础循环(
  名称: string,
  循环加速等级: number,
  输入: 基础循环输入次数,
): 循环数据 {
  const 次数 = 推导基础循环次数(输入)
  const 双倍武伤 = 次数.驱夷日破 + 次数.驱夷五明日破 + 次数.驱夷光明相日破 + 次数.驱夜断愁
  return {
    名称,
    类型: '默认',
    提供者: '用户',
    备注: `300秒循环，GCD为${(16 - 循环加速等级) / 16}秒时自动选用。以驱夜断愁次数推导月破、五明日破、光明相日破及无量次数。月破每次3段，DOT按跳数，无量按合计触发数。武伤${次数.武伤}次中${双倍武伤}次为200%（含驱夜${次数.驱夜断愁}次）、${次数.武伤 - 双倍武伤}次为100%；逐项使用驱夷、光明相和五明状态。`,
    奇穴: [...默认奇穴],
    循环详情: [
      {
        循环加速等级,
        战斗时间: 300,
        技能详情: 基础循环技能.map((项) => 创建基础循环行(项, 次数[项.技能名称])),
      },
    ],
  }
}

const 基础循环 = 创建明尊基础循环('0.8125GCD循环', 3, 基础循环输入)

export default 基础循环
