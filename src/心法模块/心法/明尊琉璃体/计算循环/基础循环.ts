export const 使用基础循环格式 = (列表: 循环技能详情[] = []) =>
  列表.some((项) => 项.技能名称 === '驱夷日破')

export const 创建基础循环行 = (技能: 基础循环技能类型, 技能数量: number): 循环技能详情 => ({
  技能名称: 技能.技能名称,
  技能数量,
  技能增益列表: [
    ...(技能.驱夷 ? ['驱夷逐法'] : []),
    ...(技能.光明相 ? ['光明相'] : []),
    ...(技能.五明 ? ['五明乐见'] : []),
  ].map((增益名称) => ({ 增益名称, 增益技能数: 技能数量 })),
})

