import type { 循环数据 } from '@/@types/循环'
import 零点七五技能 from './0.75理论循环数据.json'
import 零点八一二五技能 from './0.8125理论循环数据.json'

export const 自适应理论循环名称 = '自适应理论循环'
export const 旧理论循环名称 = ['0.75理论循环', '0.8125理论循环', '0.81理论循环']
export const 规范理论循环名称 = (名称: string) =>
  旧理论循环名称.includes(名称) ? 自适应理论循环名称 : 名称

const 自适应理论循环: 循环数据 = {
  名称: 自适应理论循环名称,
  类型: '默认',
  提供者: '模拟',
  自动选择: false,
  保留当前奇穴: true,
  强制加速要求: true,
  奇穴: [],
  备注: '300秒、40ms延迟的理论循环，普通武器、零日零月起手，驱夜衔接光明相。手动选择后，按装备与已启用增益的实际加速，在0.75与0.81GCD两套理论数据之间自动切换。原有常规循环仍优先作为默认选择。保留当前奇穴与增益，不绑定月尽天明；使用固定技能次数及实际增益窗口进行伤害对比，不随奇穴重新寻优。两档均默认戒火斩100%覆盖，团队戒火不重复叠加；炽炎镇恶使易伤失效，并按净世破魔击、赤日轮、驱夜断愁、原始戒火斩、银月斩和烈日斩的施放次数合计追加戒火斩，月破三段只计一次。',
  循环详情: [
    { 循环加速等级: 4, 战斗时间: 300, 技能详情: 零点七五技能 },
    { 循环加速等级: 3, 战斗时间: 300, 技能详情: 零点八一二五技能 },
  ],
}

/** 推荐用各档技能次数模拟，允许装备加速更高；应用后按实际档位自适应。 */
export function 获取理论档位循环(gcd: 0.75 | 0.8125): 循环数据 {
  return {
    ...自适应理论循环,
    名称: `${gcd}理论循环`,
    循环详情: 自适应理论循环.循环详情.filter(
      (详情) => Number(详情.循环加速等级) === (gcd === 0.75 ? 4 : 3),
    ),
  }
}

export default [自适应理论循环]
