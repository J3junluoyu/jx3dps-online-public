import type { 循环数据 } from '@/@types/循环'
import 零点七五技能 from './0.75理论循环数据.json'
import 零点八一二五技能 from './0.8125理论循环数据.json'

export const 自适应理论循环名称 = '自适应光明心循环'
export const 旧理论循环名称 = ['自适应理论循环', '0.75理论循环', '0.8125理论循环', '0.81理论循环']
export function 规范理论循环名称(名称: string) {
  return [...旧理论循环名称, '0.75GCD循环', '0.8125GCD循环'].includes(名称)
    ? 自适应理论循环名称
    : 名称
}
const 光明心循环: 循环数据 = {
  名称: 自适应理论循环名称,
  类型: '默认',
  提供者: '模拟',
  自动选择: false,
  保留当前奇穴: true,
  强制加速要求: true,
  奇穴: [],
  备注: '光明心循环，以战斗时间300秒、40延迟、0.75与0.81GCD自动匹配，自动适配橙武',
  循环详情: [
    {
      循环加速等级: 4,
      战斗时间: 300,
      技能详情: 零点七五技能 as 循环数据['循环详情'][0]['技能详情'],
    },
    {
      循环加速等级: 3,
      战斗时间: 300,
      技能详情: 零点八一二五技能 as 循环数据['循环详情'][0]['技能详情'],
    },
  ],
}
/** 推荐保留所选模拟档位，允许实际装备加速更高。 */
export function 获取理论档位循环(gcd: 0.75 | 0.8125): 循环数据 {
  return {
    ...光明心循环,
    名称: `${gcd}理论循环`,
    循环详情: 光明心循环.循环详情.filter(
      (详情) => Number(详情.循环加速等级) === (gcd === 0.75 ? 4 : 3),
    ),
  }
}
export default [光明心循环]
